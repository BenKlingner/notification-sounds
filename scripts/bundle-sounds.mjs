#!/usr/bin/env node
// Regenerates the plugin's bundled sounds from the sorted library in ./Sounds (managed by
// Sound Librarian). Each categorized sound is encoded as a small mono MP3 and embedded as
// base64, because plugin server code is bundled and cannot read files beside it at runtime.
//
//   node scripts/bundle-sounds.mjs [library-folder]
//
// Writes:
//   shared/bundled-sounds.ts   ids, labels, and sections (used by the client picker)
//   server/bundled-audio.ts    the MP3 data (server only, loaded on demand over RPC)
// Requires ffmpeg on the PATH.

import { execFile } from "node:child_process";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const PLUGIN_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const LIBRARY = path.resolve(process.argv[2] ?? path.join(PLUGIN_DIR, "Sounds"));
// Sections people reach for most come first; anything else follows alphabetically.
const SECTION_ORDER = ["UI", "Musical", "Game", "Voice", "Sci-Fi", "Impacts", "Whooshes"];
// Trim silence before the sound and the inaudible tail after it, then fade the last 60 ms so
// the cut never clicks. Many downloads carry seconds of near-silence, which keeps a preview
// "playing" long after the sound is over (Paseo cannot stop audio once it starts).
const TRIM = [
  "silenceremove=start_periods=1:start_threshold=-55dB:start_silence=0.01:detection=peak",
  "areverse",
  "silenceremove=start_periods=1:start_threshold=-55dB:start_silence=0.05:detection=peak",
  "afade=t=in:d=0.06",
  "areverse",
].join(",");
// Mono, 44.1 kHz, LAME VBR quality 4 (~90 kbps mono): transparent enough for short alerts.
const ENCODE_ARGS = ["-vn", "-af", TRIM, "-ac", "1", "-ar", "44100", "-c:a", "libmp3lame", "-q:a", "4", "-map_metadata", "-1", "-id3v2_version", "0"];

const { sounds } = JSON.parse(await readFile(path.join(LIBRARY, "library.json"), "utf8"));
const picked = sounds.filter((s) => s.category && !s.missing);
const rank = (section) => {
  const i = SECTION_ORDER.indexOf(section);
  return i < 0 ? SECTION_ORDER.length : i;
};
picked.sort((a, b) => rank(a.category) - rank(b.category) || a.category.localeCompare(b.category) || a.name.localeCompare(b.name));

const work = await mkdtemp(path.join(tmpdir(), "bundle-sounds-"));
const entries = [];
try {
  let next = 0;
  await Promise.all(
    Array.from({ length: 6 }, async () => {
      while (next < picked.length) {
        const index = next++;
        const sound = picked[index];
        const out = path.join(work, `${index}.mp3`);
        await run("ffmpeg", ["-hide_banner", "-loglevel", "error", "-y", "-i", path.join(LIBRARY, sound.file), ...ENCODE_ARGS, out]);
        const bytes = await readFile(out);
        entries[index] = {
          // The id is the file's path inside the library without its extension, e.g. "UI/Soft pop".
          id: sound.file.slice(0, -path.extname(sound.file).length),
          label: sound.name,
          section: sound.category,
          base64: bytes.toString("base64"),
          bytes: bytes.length,
        };
      }
    }),
  );
} finally {
  await rm(work, { recursive: true, force: true });
}

const ids = new Set();
for (const e of entries) {
  if (ids.has(e.id)) throw new Error(`Duplicate sound id: ${e.id}`);
  ids.add(e.id);
}

const header = "// Generated by scripts/bundle-sounds.mjs from the Sounds library. Do not edit by hand.\n";
const sections = [...new Set(entries.map((e) => e.section))];
await writeFile(
  path.join(PLUGIN_DIR, "shared", "bundled-sounds.ts"),
  `${header}
export interface BundledSound {
  /** Path inside the source library without the extension; also the \`bundled:\` sound reference. */
  id: string;
  label: string;
  section: string;
}

export const BUNDLED_SECTIONS: readonly string[] = ${JSON.stringify(sections)};

export const BUNDLED_SOUNDS: readonly BundledSound[] = [
${entries.map((e) => `  ${JSON.stringify({ id: e.id, label: e.label, section: e.section })},`).join("\n")}
];
`,
);
await writeFile(
  path.join(PLUGIN_DIR, "server", "bundled-audio.ts"),
  `${header}
/** Base64 MP3 data for each bundled sound, keyed by id. */
export const BUNDLED_AUDIO: Readonly<Record<string, string>> = {
${entries.map((e) => `  ${JSON.stringify(e.id)}: ${JSON.stringify(e.base64)},`).join("\n")}
};
`,
);

const total = entries.reduce((sum, e) => sum + e.bytes, 0);
console.log(`Bundled ${entries.length} sounds in ${sections.length} sections, ${(total / 1024 / 1024).toFixed(1)} MB of MP3.`);

function run(cmd, args) {
  return new Promise((resolve, reject) => {
    execFile(cmd, args, (err, _stdout, stderr) => (err ? reject(new Error(stderr || err.message)) : resolve()));
  });
}
