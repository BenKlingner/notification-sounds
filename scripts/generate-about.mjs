// Embed the approved logo so the About page works offline on every Paseo client.
// Regenerate after changing package metadata, the Paseo requirement, or the logo.
import { readFile, writeFile } from "node:fs/promises";

const root = new URL("../", import.meta.url);
const pkg = JSON.parse(await readFile(new URL("package.json", root), "utf8"));
const manifest = JSON.parse(await readFile(new URL("paseo-plugin.json", root), "utf8"));
const logo = await readFile(new URL("assets/branding/notification-sounds-logo-gradient-tall.png", root));
if (logo.subarray(0, 8).toString("hex") !== "89504e470d0a1a0a") throw new Error("Logo must be a PNG");
const metadata = {
  version: pkg.version,
  author: pkg.author,
  repository: pkg.homepage,
  paseoRequirement: manifest.requirements.paseo.replace(/^>=(\d+\.\d+\.\d+)$/, "$1 or later"),
  copyrightYear: 2026,
};
const source = "// Generated by scripts/generate-about.mjs. Do not edit by hand.\n\n"
  + `export const ABOUT = ${JSON.stringify(metadata, null, 2)} as const;\n\n`
  + `export const ABOUT_LOGO = ${JSON.stringify({
    uri: `data:image/png;base64,${logo.toString("base64")}`,
    aspectRatio: logo.readUInt32BE(16) / logo.readUInt32BE(20),
  }, null, 2)} as const;\n`;
await writeFile(new URL("client/about-data.ts", root), source);
console.log("Generated client/about-data.ts from package metadata and the approved logo.");
